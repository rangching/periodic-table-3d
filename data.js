function categoryOf(z) {
  if ([3, 11, 19, 37, 55, 87].includes(z)) return 'alkali';
  if ([4, 12, 20, 38, 56, 88].includes(z)) return 'alkaline';
  if ([5, 14, 32, 33, 51, 52].includes(z)) return 'metalloid';
  if ([1, 6, 7, 8, 15, 16, 34].includes(z)) return 'nonmetal';
  if ([9, 17, 35, 53, 85].includes(z)) return 'halogen';
  if ([2, 10, 18, 36, 54, 86].includes(z)) return 'noble';
  if (z >= 57 && z <= 71) return 'lanthanide';
  if (z >= 89 && z <= 103) return 'actinide';
  if ([13, 31, 49, 50, 81, 82, 83, 84].includes(z)) return 'post';
  return 'transition';
}

// 週期表中的位置：col 1–18，row 1–7；鑭系與錒系放在下方兩列
function placeOf(z) {
  if (z === 1) return [1, 1];
  if (z === 2) return [1, 18];
  const bands = [[3, 4, 2], [11, 12, 3], [19, 36, 4], [37, 54, 5]];
  for (const [a, b, row] of bands) {
    if (z >= a && z <= b) {
      const i = z - a;
      if (row <= 3) return [row, i < 2 ? i + 1 : i + 11];
      return [row, i + 1];
    }
  }
  if (z === 55 || z === 56) return [6, z - 54];
  if (z >= 57 && z <= 71) return [8.7, z - 57 + 3];
  if (z >= 72 && z <= 86) return [6, z - 72 + 4];
  if (z === 87 || z === 88) return [7, z - 86];
  if (z >= 89 && z <= 103) return [9.7, z - 89 + 3];
  return [7, 4]; // 104
}

