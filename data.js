// 電子組態（Aufbau 順序，未處理 Cr、Cu 等例外）
const ORDER = [[1,0],[2,0],[2,1],[3,0],[3,1],[4,0],[3,2],[4,1],[5,0],[4,2],[5,1],[6,0],[4,3],[5,2],[6,1],[7,0],[5,3],[6,2],[7,1]];
export function shellsOf(z) {
  const shells = [];
  let left = z;
  for (const [n, l] of ORDER) {
    if (left <= 0) break;
    const cap = 2 * (2 * l + 1);
    const put = Math.min(cap, left);
    shells[n - 1] = (shells[n - 1] || 0) + put;
    left -= put;
  }
  return shells.map((x) => x || 0);
}
